// Helper functions for easy querying
export function getAllProducts(): Product[] {
  return allProductsCatalog;
}

export function getProductById(id: string): Product | undefined {
  return allProductsCatalog.find((p) => p.id === id);
}

export function getProductsByCategory(category: string): Product[] {
  if (!category || category.toLowerCase() === "all" || category.toLowerCase() === "all products") {
    return allProductsCatalog;
  }
  const cleanCat = category.toLowerCase().trim();
  return allProductsCatalog.filter((p) => {
    return (
      p.category.toLowerCase().includes(cleanCat) ||
      cleanCat.includes(p.category.toLowerCase()) ||
      (p.subCategory && p.subCategory.toLowerCase().includes(cleanCat))
    );
  });
}

export function getRelatedProducts(currentId: string, limit = 4): Product[] {
  const current = getProductById(currentId);
  if (!current) return allProductsCatalog.slice(0, limit);
  return allProductsCatalog
    .filter((p) => p.id !== currentId && p.category === current.category)
    .concat(allProductsCatalog.filter((p) => p.id !== currentId && p.category !== current.category))
    .slice(0, limit);
}
